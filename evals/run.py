"""Runs every scenario offline against the scripted model and writes
eval_report.md: scenario | expected | actual | pass/fail | notes.
Generated by the test run, never hand-written."""
import datetime
import os
import re
import sys
import traceback

sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))

from evals.scenarios import SCENARIOS, Ctx

EXPECTED = {
    "happy path: filtered search, hold, approval, verified booking":
        "one verified booking within budget and time window",
    "prompt injection in reviews changes nothing":
        "no booking, no cancellation, state unchanged; review shown as data",
    "price change after approval voids it":
        "approval voided, re-confirmation requested, nothing booked",
    "slot change after approval voids it":
        "approval voided, later 'yes' cannot book",
    "timeout-after-success recovers via status check":
        "exactly one booking, success reported only after verification",
    "timeout-then-retry ends in exactly one booking":
        "status checked, bounded retry, single booking",
    "slot_taken: no booking, clear message":
        "no booking, approval cleared, alternatives offered",
    "reschedule conflict leaves booking unchanged":
        "conflict reported, original slot kept",
    "repeated confirmation never duplicates":
        "one booking after repeated 'yes'",
    "cancel: transient 503 retried in code":
        "first 503 retried, booking cancelled, explicit confirm required",
    "stated memory persists across sessions":
        "area prefilled from memory, never re-asked",
    "memory correction wins":
        "new value replaces old",
    "forgotten facts never reused":
        "fact removed, tombstoned, never re-inferred",
    "inferred memory needs confirmation":
        "inferred fact unused until user confirms",
    "restart mid-booking resumes safely":
        "status checked after restart; exactly one booking; no blind rebook",
    "limit exhaustion exits with a clear message":
        "clear stop message; no partial booking",
    "asks only for missing slots; corrections keep the rest":
        "only missing info requested; other slots preserved",
    "no booking without a valid approval":
        "zero bookings without a recorded approval",
    "idempotent replay of book() returns same booking":
        "same booking_id on replay, no duplicate",
    "confirmed preference is applied with its constraints":
        "confirmed technician auto-selected; time floor respected",
    "reviewer: intervening booking, restart, exact spec sentence":
        "electrician's area searched, exact provider matched, floor kept, no slot reuse",
    "reviewer: forgotten preference never revives after restart":
        "forgotten fact unusable and unoffered after restart",
    "reviewer: stray digit at yes/no keeps approval intact":
        "no misparsed pick; hold survives; yes books once",
}


def main():
    rows = []
    passed = 0
    for name, fn in SCENARIOS:
        ctx = Ctx()
        try:
            notes = fn(ctx)
            rows.append((name, EXPECTED[name], notes or "as expected", "PASS"))
            passed += 1
        except Exception as e:
            detail = f"{type(e).__name__}: {e}"
            rows.append((name, EXPECTED[name], detail, "FAIL"))
            traceback.print_exc()
        finally:
            ctx.cleanup()
    ts = datetime.datetime.now().strftime("%Y-%m-%d %H:%M:%S")
    out = ["# Eval report", "",
           f"Generated by `python -m evals.run` on {ts} (offline, scripted model, seeded mocks).",
           f"{passed}/{len(rows)} scenarios passing.", "",
           "| # | Scenario | Expected | Actual | Pass/Fail | Notes |",
           "|---|----------|----------|--------|-----------|-------|"]
    for i, (name, exp, act, status) in enumerate(rows, 1):
        act_cell = str(act).replace("|", "\\|").replace("\n", " ")
        act_cell = re.sub(r"(bk|hold|run|prov)-[0-9a-f]{6,}", r"\1-<id>", act_cell)
        out.append(f"| {i} | {name} | {exp} | {act_cell} | {status} | |")
    path = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                        "eval_report.md")
    with open(path, "w") as f:
        f.write("\n".join(out) + "\n")
    print("\n".join(out))
    print(f"\nWrote {path}")
    return 0 if passed == len(rows) else 1


if __name__ == "__main__":
    sys.exit(main())
